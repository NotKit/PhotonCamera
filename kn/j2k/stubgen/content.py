# --------------------------------------------------------------------------
# scraper: which types of my slice does GeckoView actually touch?
# --------------------------------------------------------------------------

IMPORT_RE = re.compile(r"^\s*import\s+(?:static\s+)?(android\.[A-Za-z0-9_.]+)\s*;", re.M)
FQN_RE = re.compile(r"\b(android\.(?:content(?:\.res|\.pm)?|database|provider)\.[A-Z][A-Za-z0-9_]*)")


def scrape():
    """Return {simple_type_name: set(files)} for types in the owned packages."""
    hits = defaultdict(set)
    for root, _dirs, files in os.walk(JAVA_SRC):
        for fn in files:
            if not fn.endswith(".java"):
                continue
            path = os.path.join(root, fn)
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            found = set()
            for fqn in IMPORT_RE.findall(text):
                pkg, _, tail = fqn.rpartition(".")
                # nested import: android.content.ClipboardManager.OnPrimaryClipChangedListener
                if pkg not in OWNED:
                    pkg2, _, tail2 = pkg.rpartition(".")
                    if pkg2 in OWNED:
                        found.add(tail2)
                    continue
                found.add(tail)
            for fqn in FQN_RE.findall(text):
                pkg, _, tail = fqn.rpartition(".")
                if pkg in OWNED:
                    found.add(tail)
            for name in found:
                hits[name].add(os.path.relpath(path, JAVA_SRC))
    return hits


