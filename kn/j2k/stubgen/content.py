def emit(check_only=False):
    written = []
    if not check_only:
        os.makedirs(OUT_DIR, exist_ok=True)
        for name, body in FILES:
            path = os.path.join(OUT_DIR, name)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(HEADER)
                fh.write("\n")
                fh.write(body)
            written.append(path)
    return written


def emit_shims(dest="/tmp/kn-content-shims"):
    os.makedirs(dest, exist_ok=True)
    for name, body in SHIM_PARTS.items():
        with open(os.path.join(dest, name), "w", encoding="utf-8") as fh:
            fh.write(body)
    return dest


DECL_RE = re.compile(r"^(?:open |abstract |final |sealed )*(?:class|interface|object)\s+([A-Za-z0-9_]+)", re.M)


def declared_types():
    names = set()
    for _name, body in FILES:
        for m in DECL_RE.finditer(body):
            names.add(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only, do not write")
    ap.add_argument("--shims", action="store_true", help="also emit cross-slice placeholders")
    args = ap.parse_args()

    hits = scrape()
    declared = declared_types()

    used = sorted(hits)
    missing = [t for t in used if t not in declared]
    extra = sorted(declared - set(used))

    written = emit(check_only=args.check)
    if args.shims:
        print("shims:", emit_shims())

    print("== android.content / .res / .pm / android.database / android.provider ==")
    print("types referenced by GeckoView Java : %d" % len(used))
    print("types declared by this generator   : %d" % len(declared))
    print("referenced but NOT declared        : %d %s" % (len(missing), missing))
    print("declared as supporting/base types  : %d %s" % (len(extra), extra))
    print()
    for t in used:
        print("  %-28s %2d file(s)" % (t, len(hits[t])))
    print()
    for p in written:
        print("wrote", p)
    print()
    print("cross-slice types referenced (owned by other groups / the java lane):")
    for f in FOREIGN:
        print("  ", f)

    return 1 if missing else 0


