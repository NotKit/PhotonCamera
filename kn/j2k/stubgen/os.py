# ---------------------------------------------------------------- scrape

def scrape(root=GV):
    import tree_sitter_java as tsj
    from tree_sitter import Language, Parser
    P = Parser(Language(tsj.language()))
    known = FROM_ATL | {"Messenger", "ResultReceiver", "StrictMode", "Trace", "ConditionVariable"}
    use = collections.defaultdict(set)

    def txt(n, s): return s[n.start_byte:n.end_byte].decode("utf8", "replace")
    def walk(n):
        yield n
        for c in n.children: yield from walk(c)

    for dp, _, fns in os.walk(root):
        for fn in fns:
            if not fn.endswith(".java"): continue
            src = open(os.path.join(dp, fn), "rb").read()
            root_node = P.parse(src).root_node
            env = {}
            for n in walk(root_node):
                if n.type in ("local_variable_declaration", "field_declaration", "formal_parameter"):
                    t = n.child_by_field_name("type")
                    if t is None: continue
                    base = txt(t, src).split("<")[0].split("[")[0].strip().split(".")[-1]
                    if base not in known: continue
                    nm = n.child_by_field_name("name")
                    if nm is not None:
                        env[txt(nm, src)] = base
                    for d in n.children:
                        if d.type == "variable_declarator":
                            dn = d.child_by_field_name("name")
                            if dn is not None: env[txt(dn, src)] = base
            for n in walk(root_node):
                k = n.type
                if k == "method_invocation":
                    o, nm = n.child_by_field_name("object"), n.child_by_field_name("name")
                    if o is None or nm is None: continue
                    ot = txt(o, src)
                    base = env.get(ot) or (ot.split(".")[-1] if ot.split(".")[-1] in known else None)
                    if base: use[base].add(txt(nm, src))
                elif k == "field_access":
                    o, f = n.child_by_field_name("object"), n.child_by_field_name("field")
                    if o is None or f is None: continue
                    ot = txt(o, src)
                    base = env.get(ot) or (ot.split(".")[-1] if ot.split(".")[-1] in known else None)
                    if base: use[base].add(txt(f, src))
                elif k == "object_creation_expression":
                    t = n.child_by_field_name("type")
                    if t is None: continue
                    base = txt(t, src).split("<")[0].strip().split(".")[-1]
                    if base in known: use[base].add("<init>")
    return use

