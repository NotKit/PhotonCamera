def build():
    parts = [HEADER, "\npackage android.os\n"]
    parts.extend(TEMPLATES)
    return "\n".join(parts) + "\n"

def audit(text, use):
    """Print members GeckoView touches that the emitted Kotlin never declares."""
    # java.lang.Object members every Kotlin type already has.
    UNIVERSAL = {"equals", "hashCode", "toString", "wait", "notify", "notifyAll", "getClass"}
    drift = {}
    for ty, members in sorted(use.items()):
        missing = []
        for m in members:
            if m == "<init>" or m in UNIVERSAL:
                continue
            pats = [" %s(" % m, " %s:" % m, "val %s" % m, "var %s" % m,
                    "object %s" % m, "class %s" % m, "interface %s" % m]
            if not any(pt in text for pt in pats):
                missing.append(m)
        if missing: drift[ty] = sorted(missing)
    return drift

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--java-deps", metavar="DIR",
                    help="also write throwaway java.io/java.util decls there (solo type-check only)")
    ap.add_argument("--no-scrape", action="store_true")
    a = ap.parse_args()

    text = build()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(text)
    print(f"wrote {a.out}  ({len(text.splitlines())} lines)")

    if a.java_deps:
        os.makedirs(a.java_deps, exist_ok=True)
        for name, body in JAVA_DEP_FILES.items():
            with open(os.path.join(a.java_deps, name), "w") as f:
                f.write(body)
        print(f"wrote java.* scratch decls to {a.java_deps}")

    if not a.no_scrape:
        use = scrape()
        print(f"scraped {len(use)} android.os types across GeckoView")
        drift = audit(text, use)
        if drift:
            print("DRIFT -- used by GeckoView, not declared in os.kt:")
            for ty, ms in drift.items():
                print(f"  {ty}: {', '.join(ms)}")
        else:
            print("no drift: every scraped member has a declaration")

if __name__ == "__main__":
    main()
