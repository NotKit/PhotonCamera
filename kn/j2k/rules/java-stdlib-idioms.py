"""Java's stdlib spelling, where the Kotlin type already exists.

Bucket "java-stdlib-idioms": Java calls a member that Kotlin spells as a
property (`arr.length`, `s.length()`, `list.size()`, `e.ordinal()`), calls
`java.lang.Object`/`Throwable` methods Kotlin renamed (`getClass`,
`getMessage`), or mutates a collection whose Java type (`java.util.List`,
`Map`, `Set`) maps onto Kotlin's *read-only* `List`/`Map`/`Set`, so `add`/
`put`/`clear` do not resolve.

Two mechanisms, and the choice between them is the whole point of the rule:

* Almost everything is fixed by a generated shim file of *extensions*, not by
  rewriting call sites.  A post-pass has no type information, and text like
  `.size()` is not safe to rewrite: this corpus really does declare
  `fun size()` (MultiMap, GeckoBundle) and `fun length()` (GeckoEditable), and
  the stubs declare more.  An extension only takes effect where the member is
  absent - exactly where the compiler is erroring - so a member always wins and
  nothing that compiles today can break.  `x.size()` where `size` is a property
  is fixed the same way: `operator fun Int.invoke()` only ever applies to the
  "expression 'size' of type 'Int' cannot be invoked" case.  Dirty, and
  deliberately so: nobody runs this code.

* Only two things must be text, because a member beats an extension there:
  `.toArray(...)` (protected in kotlin.collections.ArrayList) and
  `.toLowerCase(Locale)` / `.toUpperCase(Locale)` ("too many arguments").

The deprecated-with-ERROR stdlib calls (`String(chars)`, `remove(index)`,
`toLowerCase()`) are not rewritten at all - `DEPRECATION_ERROR` is added to the
file-level @file:Suppress, which is why this rule runs after r90_suppress.

The shim lives in one generated file, `knshim/JavaStdlibShim.kt`, and every
converted file gets `import org.mozilla.gecko.knshim.*`.  It is generated, not
hand-written: it is erased and rewritten on every run like the rest of the
output tree.

It also stays out of the stub lane's way.  `out/stubs` is scanned for what it
declares: if a real `java.lang.Class` is there, `getClass()` is left to it, and
a `java.util` type it declares keeps its import.  So the rule is correct both
with and without a stub lane, which matters because the two are being built at
the same time.
"""
import os
import re

ORDER = 95           # after r90_suppress: this rule edits the @file:Suppress it wrote
NAME = "java-stdlib-idioms"
DESCRIPTION = "Java collection/Object API spelling vs the Kotlin stdlib"

SHIM_PKG = "photoncam.knshim"
SHIM_REL = os.path.join("photoncam", "knshim", "JavaStdlibShim.kt")
SHIM_IMPORT = "import %s.*" % SHIM_PKG

PRIM_ARRAYS = ("ByteArray", "ShortArray", "IntArray", "LongArray", "CharArray",
               "FloatArray", "DoubleArray", "BooleanArray")

# java.util names that ARE a Kotlin stdlib type.  Where nothing declares
# java.util.List, the import resolves to nothing and dropping it lets the
# default kotlin.collections import supply the type - which is what the body
# type-checked against anyway.  Dropped only if the stub lane has not declared
# that type itself (see _stub_types): java.util.Iterator has a `remove()` that
# kotlin.collections.Iterator does not, so taking their stub away costs errors.
# Anything without an exact Kotlin equivalent (Arrays, Collections, Objects,
# UUID, Deque, Queue, ...) was never ours.
JAVA_UTIL_KOTLIN = {
    "List", "Map", "Set", "Collection", "Iterator", "Iterable", "Comparator",
    "ArrayList", "HashMap", "HashSet", "LinkedHashMap", "LinkedHashSet",
    "RandomAccess", "NoSuchElementException", "ConcurrentModificationException",
}
_JU_IMPORT = re.compile(r"^import java\.util\.(\w+)$")

_SUPPRESS_HEAD = re.compile(r"@file:Suppress\(")


