_DECL = re.compile(
    r"^\s*(?:public |internal |open |abstract |sealed |data |value |external )*"
    r"(?:class|interface|object|enum class|fun interface|annotation class|typealias)\s+(\w+)", re.M)
_PKG = re.compile(r"^package\s+([\w.]+)", re.M)


def _stub_types(ctx):
    """package -> {type names} declared by the stub lane, cached on ctx.

    The stub lane generates java.* stubs into out/stubs on the same run, so this
    is read fresh: what it owns, this rule leaves alone.
    """
    if "_stdlib_stub_types" in ctx:
        return ctx["_stdlib_stub_types"]
    types = {}
    stubs = os.path.join(ctx["out_root"], "stubs")
    for d, _, fs in os.walk(stubs) if os.path.isdir(stubs) else ():
        for f in fs:
            if not f.endswith(".kt"):
                continue
            try:
                text = open(os.path.join(d, f)).read()
            except OSError:
                continue
            m = _PKG.search(text)
            pkg = m.group(1) if m else ""
            types.setdefault(pkg, set()).update(_DECL.findall(text))
    ctx["_stdlib_stub_types"] = types
    return types


def _write_shim(ctx):
    dest = os.path.join(ctx["out_root"], SHIM_REL)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    have_class = "Class" in _stub_types(ctx).get("java.lang", ())
    with open(dest, "w") as fh:
        fh.write(_shim(not have_class))
    ctx["stats"]["stdlib-shim-file"] += 1


def _drop_call_args(text, marker, replacement):
    """`recv.marker(<balanced args>)` -> `recv.replacement()`.  Used where a
    member beats an extension, so the shim cannot help."""
    out, i, n = [], 0, 0
    while True:
        j = text.find(marker, i)
        if j < 0:
            out.append(text[i:])
            break
        k, depth = j + len(marker), 1
        while k < len(text) and depth:
            c = text[k]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c == '"':                      # skip a string literal
                k += 1
                while k < len(text) and text[k] != '"':
                    k += 2 if text[k] == "\\" else 1
            k += 1
        if depth:                               # unbalanced: leave it alone
            out.append(text[i:j + len(marker)])
            i = j + len(marker)
            continue
        out.append(text[i:j])
        out.append(replacement)
        i = k
        n += 1
    return "".join(out), n


def transform(unit, ctx):
    if unit.meta.get("stdlib_idioms"):
        return
    unit.meta["stdlib_idioms"] = True
    if not ctx.get("_stdlib_shim_written"):
        ctx["_stdlib_shim_written"] = True
        _write_shim(ctx)

    src = unit.kotlin

    # 1. toArray(...) is protected on kotlin.collections.ArrayList, so a member
    #    is found and an extension can never win.  Must be text.
    for marker in (".toArray(",):
        src, n = _drop_call_args(src, marker, ".toTypedArray()")
        if n:
            ctx["stats"]["toArray->toTypedArray"] += n
    # 2. toLowerCase(Locale) / toUpperCase(Locale): "too many arguments", not a
    #    deprecation, so suppression does not cover it.
    for marker, repl in ((".toLowerCase(", ".lowercase()"),
                         (".toUpperCase(", ".uppercase()")):
        src, n = _drop_call_args(src, marker, repl)
        if n:
            ctx["stats"]["case-conversion"] += n

    # 3. imports of java.util types that are Kotlin stdlib types and that the
    #    stub lane has not declared: they resolve to nothing, and the body
    #    already type-checks against kotlin.collections.
    stub_util = _stub_types(ctx).get("java.util", ())
    kept, dropped = [], 0
    for line in src.split("\n"):
        m = _JU_IMPORT.match(line.strip())
        if m and m.group(1) in JAVA_UTIL_KOTLIN and m.group(1) not in stub_util:
            dropped += 1
            continue
        kept.append(line)
    if dropped:
        src = "\n".join(kept)
        ctx["stats"]["java.util-import-dropped"] += dropped

    # 4. the shim import, right after the package declaration.
    if SHIM_IMPORT not in src and unit.package != SHIM_PKG:
        lines = src.split("\n")
        for i, l in enumerate(lines):
            if l.startswith("package "):
                lines.insert(i + 1, SHIM_IMPORT)
                break
        else:
            lines.insert(0, SHIM_IMPORT)
        src = "\n".join(lines)
        ctx["stats"]["stdlib-shim-import"] += 1

    # 5. String(chars), list.remove(index), s.toLowerCase() and friends are
    #    deprecated at ERROR level.  Suppressing beats rewriting: it needs no
    #    type information and cannot mis-target.
    if _SUPPRESS_HEAD.search(src):
        if "DEPRECATION_ERROR" not in src:
            src = _SUPPRESS_HEAD.sub('@file:Suppress("DEPRECATION_ERROR", ', src, count=1)
            ctx["stats"]["deprecation-error-suppressed"] += 1
    else:
        src = '@file:Suppress("DEPRECATION_ERROR")\n' + src
        ctx["stats"]["deprecation-error-suppressed"] += 1

    unit.kotlin = src
    unit.imports = [l for l in src.split("\n") if l.startswith("import ")]
