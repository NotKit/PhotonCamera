_DECL = re.compile(
    r"^(?:@\w+\s*)*(?:public\s+|open\s+|abstract\s+|sealed\s+|final\s+|data\s+|value\s+|enum\s+|annotation\s+|fun\s+)*"
    r"(?:class|interface|object|typealias)\s+(\w+)", re.M)


def _existing_stub_names(stub_dir):
    """(package, name) already declared by some other stub lane's file."""
    taken = set()
    if not os.path.isdir(stub_dir):
        return taken
    for f in sorted(os.listdir(stub_dir)):
        if not f.endswith(".kt") or f.startswith(MY_PREFIX):
            continue
        text = open(os.path.join(stub_dir, f)).read()
        m = re.search(r"^package\s+([\w.]+)", text, re.M)
        if not m:
            continue
        pkg = m.group(1)
        for d in _DECL.finditer(text):
            taken.add((pkg, d.group(1)))
    return taken


def emit_stubs(out_root, stats, notes):
    stub_dir = os.path.join(out_root, "stubs")
    os.makedirs(stub_dir, exist_ok=True)
    # drop our own output first, so the scan below never defers to a stale
    # copy of ourselves.
    for f in os.listdir(stub_dir):
        if f.startswith(MY_PREFIX) and f.endswith(".kt"):
            os.remove(os.path.join(stub_dir, f))
    taken = _existing_stub_names(stub_dir)

    for fname, (pkg, decls) in sorted(S.items()):
        body, skipped = [], []
        for name, code in decls:
            if (pkg, name) in taken:
                skipped.append(name)
                continue
            body.append(code.strip() + "\n")
        if not body:
            notes.append("stub-surface: %s entirely covered by another lane" % pkg)
            continue
        with open(os.path.join(stub_dir, fname + ".kt"), "w") as fh:
            fh.write(BANNER % pkg)
            if skipped:
                fh.write("// deferred to another stub lane: %s\n" % ", ".join(skipped))
            fh.write("\npackage %s\n\n" % pkg)
            fh.write("\n".join(body))
        stats["stub-surface:files"] += 1
        stats["stub-surface:decls"] += len(body)

    with open(os.path.join(stub_dir, EXT_FILE + ".kt"), "w") as fh:
        fh.write(BANNER % "missing-member")
        fh.write("\npackage %s\n" % EXT_PKG)
        fh.write(EXT_BODY)
    stats["stub-surface:files"] += 1


