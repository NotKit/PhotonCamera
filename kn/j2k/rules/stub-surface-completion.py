def transform(unit, ctx):
    if not ctx.get("_stub_surface_emitted"):
        ctx["_stub_surface_emitted"] = True
        emit_stubs(ctx["out_root"], ctx["stats"], unit.notes)

    if unit.package == EXT_PKG:
        return

    text = unit.kotlin

    # static import of a companion constant on a stub type
    def _companion(m):
        owner, const = m.group(1), m.group(2)
