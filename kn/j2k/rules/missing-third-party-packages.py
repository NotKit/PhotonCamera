# 3.  per-file import surgery.
#
# Java nested types that Kotlin will not inherit.  The declaration exists (the
# media3 stub lane emits it, top-level in the same package); the corpus just
# names it unqualified because in Java it is nested in an implemented
# interface.  Add the import when the file uses the name and imports the owner.

NESTED_IMPORTS = {
    "RequestProperties": ("androidx.media3.datasource.HttpDataSource",
                          "androidx.media3.datasource.RequestProperties"),
    "HttpDataSourceException": ("androidx.media3.datasource.HttpDataSource",
                                "androidx.media3.datasource.HttpDataSourceException"),
    "InvalidResponseCodeException": ("androidx.media3.datasource.HttpDataSource",
                                     "androidx.media3.datasource.InvalidResponseCodeException"),
    "InvalidContentTypeException": ("androidx.media3.datasource.HttpDataSource",
                                    "androidx.media3.datasource.InvalidContentTypeException"),
}

# `Spanned.nextSpanTransition(int, int, Class)` is raw in the Android SDK, so
# GeckoEditable's override is raw too and Kotlin wants an argument.
_RAW_CLASS_PARAM = re.compile(r"(fun nextSpanTransition\([^)]*?type: )Class(\??)\)")

# Java's CharSequence.subSequence is non-null; the converter emitted `CharSequence?`
# for it, which does not override kotlin.CharSequence's member.  The one body this
# hits throws, so tightening the return type cannot change behaviour.
_SUBSEQUENCE_RET = re.compile(
    r"(override fun subSequence\(\w+: Int, \w+: Int\): CharSequence)\?")

_DECL = re.compile(
    r"^(?:@\w+\s*)*(?:public\s+|open\s+|abstract\s+|sealed\s+|final\s+|data\s+|value\s+|enum\s+|annotation\s+|fun\s+)*"
    r"(?:class|interface|object|typealias)\s+(\w+)", re.M)


def _existing_stub_names(stub_dir):
    """(package, name) some other stub lane already declares."""
    taken = set()
    if not os.path.isdir(stub_dir):
        return taken
    for f in sorted(os.listdir(stub_dir)):
        if not f.endswith(".kt") or f.startswith(MY_PREFIX):
            continue
        text = open(os.path.join(stub_dir, f)).read()
        m = re.search(r"^package\s+([\w.]+)", text, re.M)
        if not m:
            continue
        pkg = m.group(1)
        for d in _DECL.finditer(text):
            taken.add((pkg, d.group(1)))
    return taken


def emit_stubs(out_root, stats, notes):
    stub_dir = os.path.join(out_root, "stubs")
    os.makedirs(stub_dir, exist_ok=True)
    for f in os.listdir(stub_dir):
        if f.startswith(MY_PREFIX) and f.endswith(".kt"):
            os.remove(os.path.join(stub_dir, f))
    taken = _existing_stub_names(stub_dir)

    for fname, (pkg, decls) in sorted(S.items()):
        body, skipped, heads = [], [], []
        for name, code in decls:
            if (pkg, name) in taken:
                skipped.append(name)
                continue
            # imports are written next to the declaration that needs them;
            # Kotlin wants them all at the top of the file.
            keep = []
            for line in code.strip().split("\n"):
                if line.startswith("import "):
                    if line not in heads:
                        heads.append(line)
                else:
                    keep.append(line)
            body.append("\n".join(keep).strip() + "\n")
        if not body:
            notes.append("third-party: %s entirely covered by another lane" % pkg)
            continue
        if skipped:
            # A partial overlap is worse than none: the members we do not
            # declare are the ones another lane was missing.  Say so.
            notes.append("third-party: %s deferred to another lane: %s"
                         % (pkg, ", ".join(skipped)))
        with open(os.path.join(stub_dir, fname + ".kt"), "w") as fh:
            fh.write(BANNER % pkg)
            fh.write("\npackage %s\n\n" % pkg)
            if heads:
                fh.write("\n".join(heads) + "\n\n")
            fh.write("\n".join(body))
        stats["third-party:files"] += 1
        stats["third-party:decls"] += len(body)

    with open(os.path.join(stub_dir, EXT_FILE + ".kt"), "w") as fh:
        fh.write(BANNER % "call-site extensions")
        fh.write("\npackage %s\n" % EXT_PKG)
        fh.write(EXT_BODY)
    stats["third-party:files"] += 1


