"""Stub the third-party packages nothing in the tree declares at all.

Round 3's biggest single error bucket was not a bad conversion: it was four
whole package families GeckoView imports that no stub lane had scraped, so
every reference in the importing file cascaded off one unresolved package root.

  * `android.text`, `.style`, `.method`, `.format` - Editable/Spanned/Spannable
    and the span API, TextUtils, Selection, InputType, TextPaint.  GeckoEditable
    *implements* `Editable`, so these are not free-form: the interface members
    have to match, signature for signature, the `override fun`s the converter
    already emitted (`fun length()`, not `val length`; `Class<T>?`, not KClass).
    `SpannableString`/`SpannableStringBuilder` additionally implement
    kotlin.CharSequence, because corpus code assigns them to `CharSequence`
    fields; a class can carry both `fun length()` and `override val length`.
  * `com.google.android.gms.fido.*` + `com.google.android.gms.tasks.Task` -
    the whole WebAuthn Fido2 builder surface.  Dead weight for the port; it is
    stubbed only so WebAuthnTokenManager.kt stops cascading.
  * `com.google.common.net.HttpHeaders` / `com.google.common.base.Predicate`.
  * `org.yaml.snakeyaml` - Raptor's debug-config reader.

Plus three small things that live in the same files:

  1. `java.util.stream` - three `.stream()` call sites.  A `Stream<T>` stub and
     an `Iterable<T>.stream()` extension.
  2. Java resolves `X.class` where Kotlin has `X::class`, so the `Class<T>?`
     members of `Spanned` are unreachable from the call sites.  KClass-taking
     *extensions* of `getSpans`/`nextSpanTransition` sit beside them; an
     extension is only picked when no member applies, so this cannot change a
     call site that already compiles.
  3. `RequestProperties` and `HttpDataSourceException` ARE declared (the media3
     stub lane has them, top-level) but the corpus refers to them unqualified,
     because in Java they are nested in the `HttpDataSource` interface that
     HttpChannelDataSource implements.  Kotlin does not inherit nested types:
     the fix is an import line, so one is added.

Every body is TODO().  None of it is meant to run.
"""
