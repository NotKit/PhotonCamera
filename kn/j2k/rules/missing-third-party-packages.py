def transform(unit, ctx):
    if not ctx.get("_thirdparty_emitted"):
        ctx["_thirdparty_emitted"] = True
        emit_stubs(ctx["out_root"], ctx["stats"], unit.notes)

    if unit.package == EXT_PKG:
        return

    text = unit.kotlin

    n = len(_RAW_CLASS_PARAM.findall(text))
    if n:
        text = _RAW_CLASS_PARAM.sub(r"\1Class<*>\2)", text)
        ctx["stats"]["third-party:raw-class-param"] += n

    if "import android.text.Editable" in text:
        n = len(_SUBSEQUENCE_RET.findall(text))
        if n:
            text = _SUBSEQUENCE_RET.sub(r"\1", text)
            ctx["stats"]["third-party:subsequence-return"] += n

    lines = text.split("\n")
    imports = set(l.strip() for l in lines if l.startswith("import "))
    body = "\n".join(l for l in lines if not l.startswith("import "))

    add = []
    for name, (owner, imp) in sorted(NESTED_IMPORTS.items()):
        if ("import " + owner) not in imports:
            continue
        if ("import " + imp) in imports:
            continue
        if re.search(r"\b%s\b" % re.escape(name), body):
            add.append("import " + imp)
    if any(rx.search(body) for rx in EXT_TRIGGERS) and EXT_IMPORT not in imports:
        add.append(EXT_IMPORT)

    if add:
        out, done = [], False
        for l in lines:
            out.append(l)
            if not done and l.startswith("package "):
                out.extend(add)
                done = True
        if done:
            lines = out
            ctx["stats"]["third-party:imports"] += len(add)

    unit.kotlin = "\n".join(lines)
    unit.imports = [l for l in lines if l.startswith("import ")]
