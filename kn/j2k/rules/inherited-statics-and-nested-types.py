_TOKEN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def _line_bounds(text, pos):
    start = text.rfind("\n", 0, pos) + 1
    end = text.find("\n", pos)
    return start, (len(text) if end < 0 else end)


def _apply(unit, subs, forced, declared):
    """Rewrite bare `name` -> `subs[name].name`.  Returns the number of edits."""
    text = unit.kotlin
    masked = _mask(text)
    pieces = []
    last = 0
    edits = 0

    for m in _TOKEN.finditer(masked):
        name = m.group(0)
        owner = subs.get(name)
        if owner is None:
            continue
        if name in declared and name not in forced:
            continue
        s, e = m.start(), m.end()
        ls, le = _line_bounds(masked, s)
        head = masked[ls:s]
        if head.lstrip().startswith(("import ", "package ", "@")):
            continue
        prev = head.rstrip()
        if prev.endswith((".", "@", "`", "?", "::")):
            continue
        if masked[e:e + 1] == "`":
            continue
        words = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", prev)
        if words and words[-1] in _DECL_KEYWORDS:
            continue
        pieces.append(text[last:s])
        pieces.append(owner + "." + name)
        last = e
        edits += 1

    if edits:
        pieces.append(text[last:])
        unit.kotlin = "".join(pieces)
    return edits


def _apply_when_enums(unit, enum_subs, declared):
    """`HTTP ->` inside a `when`, where HTTP is a constant of a stub enum.

    The match is anchored on a whole branch line ending in `->`, which is the
    one shape an enum *entry* can never have: an earlier version matched a
    trailing comma too and happily rewrote `NONE,` inside four `enum class`
    bodies into a fully qualified name, which is a syntax error.
    """
    if not enum_subs:
        return 0
    text = unit.kotlin
    masked = _mask(text)
    pieces = []
    last = 0
    edits = 0
    branch = re.compile(r"(?m)^[ \t]*([A-Za-z_][A-Za-z0-9_]*"
                        r"(?:[ \t]*,[ \t]*[A-Za-z_][A-Za-z0-9_]*)*)[ \t]*->")
    label = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
    for m in branch.finditer(masked):
        for lm in label.finditer(masked, m.start(1), m.end(1)):
            name = lm.group(0)
            owner = enum_subs.get(name)
            if owner is None or name in declared:
                continue
            pieces.append(text[last:lm.start()])
            pieces.append(owner + "." + name)
            last = lm.end()
            edits += 1
    if edits:
        pieces.append(text[last:])
        unit.kotlin = "".join(pieces)
    return edits


def _kt_class_block(text, simple):
    """(start, end) of the `class <simple>` block in the generated Kotlin, by indent."""
    m = re.search(r"(?m)^(\s*)(?:[\w]+\s+)*(?:class|object|interface)\s+"
                  + re.escape(simple) + r"\b", text)
    if m is None:
        return None
    indent = len(m.group(1))
    start = m.start()
    nl = text.find("\n", m.end())
    if nl < 0:
        return start, len(text)
    for line_m in re.finditer(r"(?m)^([ \t]*)\S", text[nl + 1:]):
        if len(line_m.group(1)) <= indent:
            return start, nl + 1 + line_m.start()
    return start, len(text)


def _apply_qualified_new(unit, sites):
    """`recv.new Inner(a)` came out as `Inner(a)`; Kotlin spells it `with(recv) { Inner(a) }`."""
    text = unit.kotlin
    edits = 0
    for enclosing, recv, inner in sites:
        span = _kt_class_block(text, enclosing) if enclosing else (0, len(text))
        if span is None:
            continue
        lo, hi = span
        pat = re.compile(r"(?<![\w.])" + re.escape(inner) + r"\(\s*\)")
        chunk, n = pat.subn("with(%s!!) { %s() }" % (recv, inner), text[lo:hi])
        if n:
            text = text[:lo] + chunk + text[hi:]
            edits += n
    if edits:
        unit.kotlin = text
    return edits


_DECLARED = re.compile(
    r"\b(?:val|var|fun|class|interface|object|typealias|annotation\s+class|"
    r"enum\s+class)\s+(?:<[^>\n]*>\s*)?([A-Za-z_][A-Za-z0-9_]*)")


def transform(unit, ctx):
    idx = _build_index(ctx)

    own = idx["by_file"].get(unit.java_path, [])
    if not own and unit.java_path not in idx["static_imports"]:
        return

    declared = set(_DECLARED.findall(_mask(unit.kotlin)))
    own_set = set(own)

    subs = {}
    for fqn in own:
        for anc in _closure(idx, fqn, None):
            if anc in own_set:
                continue                       # nested in this very file; already in scope
            rec = idx["types"].get(anc)
            if rec is None:
                continue
            for c in rec["consts"]:
                subs.setdefault(c, anc)
            for nm, nested_fqn in rec["nested"].items():
                nested = idx["types"].get(nested_fqn)
                if nested is None or not nested["static"]:
                    # A non-static nested class is `inner` in Kotlin, and an
                    # inner constructor cannot be reached through a type name
                    # at all - `RuntimeSettings.Pref(...)` is an error where
                    # bare `Pref(...)` inside a subclass is not.  Kotlin does
                    # carry a superclass's nested classifiers into scope; it is
                    # the ones inherited through an *interface* that go
                    # missing, and those are always static.
                    continue
                subs.setdefault(nm, anc)

    forced = {}
    for member, owner in idx["static_imports"].get(unit.java_path, {}).items():
        if owner.startswith(("java.lang.annotation", "androidx.", "android.")):
            continue
        subs[member] = owner
        forced[member] = owner

    n = _apply(unit, subs, forced, declared)

    # The `import static` line itself: j2k copies it through as
    # `import a.b.C.NAME`, which Kotlin reads as a member of the *class* C and
    # cannot find, because j2k put NAME in C's companion.  Every use site is
    # qualified above, so the import has no work left to do - drop it rather
    # than respell it `a.b.C.Companion.NAME`, which would be wrong the moment
    # a constant lands somewhere other than a companion.
    if forced:
        kept = []
        for line in unit.kotlin.split("\n"):
            stripped = line.strip()
            if stripped.startswith("import "):
                path = stripped[len("import "):].strip()
                member = path.rsplit(".", 1)[-1]
                if member in forced and path == forced[member] + "." + member:
                    n += 1
                    continue
            kept.append(line)
        unit.kotlin = "\n".join(kept)

    # Stub enum constants, for `when` branches j2k could not qualify: it only
    # knows the enums in the Java corpus, so `java.net.Proxy.Type` is invisible
    # to it.  Ambiguous names are skipped, and so is anything the corpus index
    # already claims as an enum constant - that one belongs to j2k.
    corpus_enums = getattr(ctx.get("index"), "enum_consts", {})
    enum_subs = {}
    for nm, owners in idx["stub_enum_consts"].items():
        if len(owners) == 1 and nm not in declared and nm not in corpus_enums:
            enum_subs[nm] = next(iter(owners))
    n += _apply_when_enums(unit, enum_subs, declared)

    sites = idx["qualified_new"].get(unit.java_path, [])
    if sites:
        k = _apply_qualified_new(unit, sites)
        n += k
        if k:
            unit.notes.append(
                "%s: rewrote %d qualified inner-class creation(s) `recv.new T()` "
                "as `with(recv) { T() }`" % (NAME, k))

    if n:
        ctx["stats"][NAME] += n
