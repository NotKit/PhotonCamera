# index: the Kotlin stub tree (everything under out_root that j2k did not write)

_KT_TYPE = re.compile(
    r"^\s*(?:(?:public|internal|private|protected|open|abstract|sealed|final|"
    r"inner|external|expect|actual|annotation|data|value|enum|fun)\s+)*"
    r"(?P<kw>class|interface|object)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)")
_KT_COMPANION = re.compile(r"^\s*companion\s+object\b")
_KT_VAL = re.compile(r"^\s*(?:(?:public|internal|private|protected|const|"
                     r"lateinit|override|open|final|external|actual)\s+)*"
                     r"(?:val|var)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)")
_KT_IDENTS = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*\s*[,;]?$")


def _kt_supers(line):
    """Supertype simple names out of a Kotlin declaration header."""
    head = line.split("{")[0]
    if ":" not in head:
        return []
    tail = head.split(":", 1)[1]
    tail = re.sub(r"\([^()]*\)", "", tail)
    out = []
    for part in tail.split(","):
        part = part.split("<")[0].strip()
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*", part or ""):
            out.append(part)
    return out


def _index_kotlin_stub(idx, text):
    pkg = ""
    m = re.search(r"^package\s+([\w.]+)", text, re.M)
    if m:
        pkg = m.group(1)

    stack = []          # [(rec_or_None, depth_at_open, is_companion)]
    depth = 0
    pending = None      # (rec, is_companion) waiting for its `{`
    in_enum_head = None

    for raw in _mask(text).split("\n"):
        line = raw.rstrip()
        stripped = line.strip()

        if in_enum_head is not None and stripped and _KT_IDENTS.match(stripped):
            for nm in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", stripped):
                in_enum_head["enum_consts"].add(nm)
                idx["stub_enum_consts"].setdefault(nm, set()).add(in_enum_head["fqn"])

        owner = None
        for rec, _d, is_comp in reversed(stack):
            if rec is not None:
                owner = rec
                break

        mt = _KT_TYPE.match(line)
        if mt and pending is None:
            nm = mt.group("name")
            parent = owner
            parts = ([parent["fqn"]] if parent else ([pkg] if pkg else []))
            fqn = ".".join([p for p in parts if p] + [nm])
            kind = "object" if mt.group("kw") == "object" else mt.group("kw")
            if re.search(r"\benum\s+class\b", line):
                kind = "enum"
            rec = _new_type(fqn, kind, pkg, True)
            rec["supers"] = _kt_supers(line)
            idx["types"].setdefault(fqn, rec)
            rec = idx["types"][fqn]
            idx["by_simple"].setdefault(nm, []).append(fqn)
            if parent is not None:
                parent["nested"][nm] = fqn
            if kind in ("interface", "object", "enum"):
                pending = (rec, False)
            else:
                pending = (rec, False)
            # single-line `enum class T { A, B, C }`
            if kind == "enum" and "{" in line and "}" in line:
                inner = line[line.index("{") + 1:line.rindex("}")]
                for nm2 in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", inner.split(";")[0]):
                    rec["enum_consts"].add(nm2)
                    idx["stub_enum_consts"].setdefault(nm2, set()).add(fqn)
        elif _KT_COMPANION.match(line) and pending is None:
            pending = (None, True)
        else:
            mv = _KT_VAL.match(line)
            if mv is not None and owner is not None:
                in_static = False
                for rec2, _d, is_comp in reversed(stack):
                    if is_comp:
                        in_static = True
                        break
                    if rec2 is not None:
                        in_static = rec2["kind"] in ("object", "interface", "annotation")
                        break
                if in_static:
                    owner["consts"].add(mv.group("name"))

        for ch in line:
            if ch == "{":
                depth += 1
                if pending is not None:
                    stack.append((pending[0], depth, pending[1]))
                    if pending[0] is not None and pending[0]["kind"] == "enum":
                        in_enum_head = pending[0]
                    pending = None
            elif ch == "}":
                if stack and stack[-1][1] == depth:
                    if in_enum_head is not None and stack[-1][0] is in_enum_head:
                        in_enum_head = None
                    stack.pop()
                depth -= 1
        if in_enum_head is not None and ";" in line:
            in_enum_head = None


