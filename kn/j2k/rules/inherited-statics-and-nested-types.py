# resolution

def _resolve(idx, raw, from_fqn):
    """A supertype name, as written, against the corpus + stub index."""
    raw = raw.split("<")[0].strip()
    if not raw:
        return None
    if raw in idx["types"]:
        return raw
    # enclosing scopes of the referring type, innermost first
    parts = from_fqn.split(".")
    for i in range(len(parts), 0, -1):
        cand = ".".join(parts[:i]) + "." + raw
        if cand in idx["types"]:
            return cand
    pkg = idx["types"].get(from_fqn, {}).get("pkg", "")
    if pkg and (pkg + "." + raw) in idx["types"]:
        return pkg + "." + raw
    simple = raw.split(".")[-1]
    hits = [f for f in idx["by_simple"].get(simple, [])
            if f == raw or f.endswith("." + raw)]
    if len(hits) == 1:
        return hits[0]
    hits = idx["by_simple"].get(simple, [])
    if len(hits) == 1:
        return hits[0]
    return None


def _closure(idx, fqn, seen):
    """Strict supertype closure of `fqn`, as fqns."""
    out = []
    stack = list(idx["types"].get(fqn, {}).get("supers", []))
    local = set()
    while stack:
        raw = stack.pop()
        got = _resolve(idx, raw, fqn)
        if got is None or got in local or got == fqn:
            continue
        local.add(got)
        out.append(got)
        stack.extend(idx["types"].get(got, {}).get("supers", []))
    return out


