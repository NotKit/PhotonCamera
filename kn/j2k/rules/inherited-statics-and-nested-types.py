def _build_index(ctx):
    idx = ctx.get("_inh_idx")
    if idx is not None:
        return idx
    idx = {"types": {}, "by_simple": {}, "by_file": {},
           "static_imports": {}, "stub_enum_consts": {}, "qualified_new": {}}

    parser = Parser(_JAVA)
    src_root = ctx["src_root"]
    for d, _dirs, fs in os.walk(src_root):
        for f in sorted(fs):
            if not f.endswith(".java"):
                continue
            p = os.path.join(d, f)
            try:
                src = open(p, "rb").read()
                tree = parser.parse(src)
                if tree.root_node.has_error:
                    continue
                _index_java(idx, p, src, tree)
                _index_qualified_new(idx, p, src, tree)
            except Exception:                                # noqa: BLE001
                continue

    out_root = ctx.get("out_root")
    if out_root and os.path.isdir(out_root):
        for d, _dirs, fs in os.walk(out_root):
            for f in sorted(fs):
                if not f.endswith(".kt"):
                    continue
                p = os.path.join(d, f)
                try:
                    text = open(p, encoding="utf-8", errors="replace").read()
                except Exception:                            # noqa: BLE001
                    continue
                if "Generated by kn-run/j2k.py" in text[:400]:
                    continue                                  # j2k output; the Java index has it
                try:
                    _index_kotlin_stub(idx, text)
                except Exception:                            # noqa: BLE001
                    continue

    ctx["_inh_idx"] = idx
    return idx


def _index_qualified_new(idx, path, src, tree):
    """`recv.new Inner(args)` sites - Kotlin has no spelling, j2k drops `recv.`.

    The enclosing type is recorded with each site so the rewrite can be
    confined to that class's block: `this.new Inner()` elsewhere in the same
    file converts to the same bare `Inner()` and is already correct Kotlin.
    """
    sites = []

    def walk(node, enclosing):
        if node.type in _TYPE_DECLS:
            nm = node.child_by_field_name("name")
            if nm is not None:
                enclosing = _txt(src, nm)
        if node.type == "object_creation_expression":
            head = src[node.start_byte:node.end_byte].decode("utf-8", "replace")
            m = re.match(r"^([A-Za-z_][A-Za-z0-9_.]*)\s*\.\s*new\s+"
                         r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", head)
            if m and m.group(1) != "this":
                sites.append((enclosing, m.group(1), m.group(2)))
        for c in node.children:
            walk(c, enclosing)

    walk(tree.root_node, None)
    if sites:
        idx["qualified_new"][path] = sites


