"""Qualify what Java inherits into scope and Kotlin does not: static constants and nested types.

Java resolves a simple name against the *inherited* scope of every enclosing
class: an implementor of `GeckoSession.SelectionActionDelegate` writes bare
`ACTION_COPY` and bare `Selection`, and javac walks up the supertype chain to
find the interface constant and the nested class.  Kotlin inherits neither.
A companion object is not inherited, and neither are nested classifiers, so
every one of those names is an `unresolved reference`.

Three shapes land in this bucket, all fixed the same way - by rewriting the
bare name to a fully qualified one:

  * inherited static constants      ACTION_CUT, HIDE_REASON_*, IME_STATE_DISABLED
  * inherited nested classifiers    Selection, Callbacks, TrackType, DemuxerError
  * `import static a.b.C.NAME`      Kotlin needs `C.Companion.NAME`, and j2k
                                    either drops the import or emits a path
                                    that skips `Companion`

The qualified spelling is always the *fully qualified* one
(`org.mozilla.geckoview.GeckoSession.SelectionActionDelegate.ACTION_CUT`)
rather than the shortest one that would work.  It needs no import, it cannot
collide with a wildcard import, and - the case that decided it - it beats a
single-type import of the same simple name.  `BasicSelectionActionDelegate`
imports `android.text.Selection` and means
`GeckoSession.SelectionActionDelegate.Selection`; Java's inherited scope wins
over an import there, and only a fully qualified name reproduces that.

Cost of getting it wrong is why the two indexes are separate:

  * the Java corpus is parsed with tree-sitter, so nesting, `static`, and the
    implicit `static final` on interface fields are real facts, not guesses.
  * the stub tree (`geckoview-kn/src/**` files not generated by j2k) is scanned
    line-wise for the same facts.  It is needed because a supertype chain
    leaves the corpus: `GeckoInputConnection` -> `BaseInputConnection` ->
    `android.view.inputmethod.InputConnection`, which is where
    `GET_TEXT_WITH_STYLES` lives.

A name is left alone if it is declared anywhere in the file being rewritten.
That is coarser than real scoping - a constant inherited by one class and
shadowed by a local `val` in another would be skipped - but it is the cheap
direction to be wrong in, and it is what keeps the pass from touching a name
that already resolves.  The exception is a name that came from an
`import static`: the import is proof of where the name comes from, so those
are rewritten even when the same file also declares them (`ExperimentDelegate`
static-imports a constant out of its own nested `ExperimentException`).
Declaration sites themselves are always skipped, as are comments, strings,
`import`/`package` lines, and anything already qualified.

One extra, same shape: a `when` branch that is a bare enum constant of a *stub*
enum.  j2k qualifies `case CONST:` from its corpus enum index, which does not
cover `java.net.Proxy.Type`, so `HTTP ->` and `SOCKS ->` in `GeckoAppShell`
stay unresolved.  Qualified only where the constant name is unique across the
whole stub tree.

Two things this rule deliberately does *not* qualify:

  * a nested type that is not static.  Kotlin does carry a superclass's nested
    classifiers into scope - it is the ones inherited through an *interface*
    that go missing - and a non-static nested class is `inner` in Kotlin, whose
    constructor cannot be reached through a type name at all.  Writing
    `RuntimeSettings.Pref(...)` where bare `Pref(...)` already worked cost 109
    new errors before this exclusion existed.
  * a `when` branch that looks like an enum constant but sits in an `enum
    class` body.  Matching a trailing comma as well as `->` rewrote four enum
    declarations into syntax errors.

The one thing here that is not a qualification: `recv.new Inner()`.  Java's
qualified inner-class creation loses its receiver in conversion, so
`ServiceAllocator` calls `DefaultBindDelegate()` / `IsolatedBindDelegate()`
bare.  Qualifying those would only trade one error for another, so they become
`with(recv!!) { Inner() }` - the one spelling Kotlin accepts - driven off the
Java AST, and confined to the block of the class the Java site was in, because
a `this.new Inner()` elsewhere in the same file converts to the same bare text
and is already correct.

Measured by ablation on the round-4 tree, whole corpus, klib: the same tree
generated with every other rule and this one switched off has 92 errors in this
bucket - 54 of them in BasicSelectionActionDelegate, where the unresolved
nested `Selection` also costs 14 `smart cast to TypeVariable(K)` and every
member read off it - against 0 with the rule on.  Corpus total in that ablation
was 106; the rest belongs to other buckets (SessionState's Kotlin-builtin
overrides, `Short.or` in GeckoScreenOrientation, WebResponse.Builder.mBody).
"""
import os
import re

from tree_sitter import Language, Parser
import tree_sitter_java

ORDER = 75                 # after the stub generators (50-65) and java-declaration-forms (70):
                           # they key off simple names, so qualify only once they are done
NAME = "inherited-statics-and-nested-types"
DESCRIPTION = ("qualify inherited constants / nested types and static imports - "
               "Kotlin inherits neither companions nor nested classifiers")

_JAVA = Language(tree_sitter_java.language())

_TYPE_DECLS = ("class_declaration", "interface_declaration",
               "enum_declaration", "annotation_type_declaration",
               "record_declaration")

_KIND = {"class_declaration": "class", "interface_declaration": "interface",
         "enum_declaration": "enum", "annotation_type_declaration": "annotation",
         "record_declaration": "class"}

# Members of these are static whether or not anybody wrote `static`.
_IMPLICIT_STATIC = ("interface", "annotation")

_DECL_KEYWORDS = {"val", "var", "fun", "class", "interface", "object",
                  "typealias", "enum", "annotation", "constructor"}


# --------------------------------------------------------------------------
# masking: blank out comments and string literals so a token scan sees code only

def _mask(text):
    """Same-length copy of `text` with comments and strings replaced by spaces."""
    out = list(text)
    i, n = 0, len(text)
    depth = 0                       # /* */ nesting (Kotlin nests them)
    while i < n:
        c = text[i]
        if depth:
            if text.startswith("/*", i):
                depth += 1
                out[i] = out[i + 1] = " "
                i += 2
                continue
            if text.startswith("*/", i):
                depth -= 1
                out[i] = out[i + 1] = " "
                i += 2
                continue
            if c != "\n":
                out[i] = " "
            i += 1
            continue
        if text.startswith("/*", i):
            depth = 1
            out[i] = out[i + 1] = " "
            i += 2
            continue
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
            continue
        if text.startswith('"""', i):
            out[i] = out[i + 1] = out[i + 2] = " "
            i += 3
            while i < n and not text.startswith('"""', i):
                if text[i] != "\n":
                    out[i] = " "
                i += 1
            for k in range(i, min(i + 3, n)):
                out[k] = " "
            i += 3
            continue
        if c in ('"', "'"):
            quote = c
            out[i] = " "
            i += 1
            while i < n and text[i] != quote:
                if text[i] == "\\":
                    out[i] = " "
                    i += 1
                    if i < n and text[i] != "\n":
                        out[i] = " "
                        i += 1
                    continue
                if text[i] == "\n":         # unterminated; bail out of the literal
                    break
                out[i] = " "
                i += 1
            if i < n and text[i] == quote:
                out[i] = " "
                i += 1
            continue
        i += 1
    return "".join(out)


