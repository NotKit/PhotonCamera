# index: the Java corpus

def _txt(src, node):
    if node is None:
        return ""
    return src[node.start_byte:node.end_byte].decode("utf-8", "replace")


def _modifier_words(src, node):
    for c in node.children:
        if c.type == "modifiers":
            return set(_txt(src, c).split())
    return set()


def _declarator_names(src, node):
    """Field names out of a field_declaration / constant_declaration."""
    names = []
    for c in node.named_children:
        if c.type == "variable_declarator":
            nm = c.child_by_field_name("name")
            if nm is not None:
                names.append(_txt(src, nm))
    return names


def _new_type(fqn, kind, pkg, static):
    return {"fqn": fqn, "kind": kind, "pkg": pkg, "static": static,
            "supers": [], "consts": set(), "nested": {}, "enum_consts": set()}


def _index_java(idx, path, src, tree):
    pkg = ""
    for c in tree.root_node.named_children:
        if c.type == "package_declaration":
            pkg = re.sub(r"^package\s+|;\s*$", "", _txt(src, c).strip()).strip()
            break

    statics = idx["static_imports"].setdefault(path, {})
    for c in tree.root_node.named_children:
        if c.type == "import_declaration" and "static" in _txt(src, c):
            body = re.sub(r"^import\s+static\s+|;\s*$", "", _txt(src, c).strip()).strip()
            if body.endswith("*") or "." not in body:
                continue
            owner, _, member = body.rpartition(".")
            statics[member] = owner

    def walk(node, prefix, container):
        for child in node.named_children:
            t = child.type
            if t not in _TYPE_DECLS:
                walk(child, prefix, container)
                continue
            nm = _txt(src, child.child_by_field_name("name"))
            if not nm:
                continue
            path_parts = prefix + [nm]
            fqn = (pkg + "." if pkg else "") + ".".join(path_parts)
            kind = _KIND[t]
            mods = _modifier_words(src, child)
            # "static" in the Kotlin sense: a nested type that needs no outer
            # instance.  Java writes it explicitly only some of the time -
            # interfaces, annotations, enums and records always are, and
            # anything declared inside an interface is too.
            is_static = (not prefix
                         or "static" in mods
                         or kind in ("interface", "annotation", "enum")
                         or t == "record_declaration"
                         or (container is not None
                             and container["kind"] in _IMPLICIT_STATIC))
            rec = _new_type(fqn, kind, pkg, is_static)
            idx["types"][fqn] = rec
            idx["by_simple"].setdefault(nm, []).append(fqn)
            idx["by_file"].setdefault(path, []).append(fqn)
            if container is not None:
                container["nested"][nm] = fqn

            for sc in child.named_children:
                if sc.type == "superclass":
                    for k in sc.named_children:
                        rec["supers"].append(_txt(src, k).split("<")[0].strip())
                elif sc.type in ("super_interfaces", "extends_interfaces"):
                    for tl in sc.named_children:
                        kids = tl.named_children if tl.type == "type_list" else [tl]
                        for k in kids:
                            rec["supers"].append(_txt(src, k).split("<")[0].strip())

            body = child.child_by_field_name("body")
            if body is None:
                continue
            implicit = kind in _IMPLICIT_STATIC

            def members(container_node):
                for m in container_node.named_children:
                    if m.type in ("field_declaration", "constant_declaration"):
                        if implicit or "static" in _modifier_words(src, m):
                            rec["consts"].update(_declarator_names(src, m))
                    elif m.type == "enum_constant":
                        rec["enum_consts"].add(
                            _txt(src, m.child_by_field_name("name")))
                    elif m.type == "enum_body_declarations":
                        members(m)

            members(body)
            walk(body, path_parts, rec)

    walk(tree.root_node, [], None)


