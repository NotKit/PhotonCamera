"""Give the port a java.*/javax.*/dalvik.* surface, and import it.

Kotlin/Native has no JDK.  Nothing under `java.` resolves, which costs twice:
once for every `import java....` line, and again for every use site plus every
member invoked on a receiver whose type never resolved.  It was the single
largest root cause in the round-1 log (~2000 of 5902 errors).

Two halves, the same shape as `stubgen/os.py`:

  1. A klib-local stub package per JDK package we touch, emitted once per run
     into `<out>/stubs/jdk_*.kt`.  Every body is TODO(); nothing here runs.
     Names another stub file already declares (`java.lang.Runnable`,
     `java.util.Locale` from `stubgen/view.py`) are skipped, so the two lanes
     can coexist and this stays re-runnable.

  2. A per-file import pass.  `java.lang` is implicit in Java and explicit in
     Kotlin, so `Math`, `Thread`, `Integer`, `Class`, `Runnable` and friends
     need an import line the Java never had.

Three things the JDK does that Kotlin spells differently are handled by
rewriting rather than stubbing:

  * `java.util.List/Map/Set/...` are typealiases onto Kotlin's *mutable*
    collections.  Java code calls `add`/`put` on them, and a stub hierarchy of
    our own would not interoperate with the collections the android.* stubs
    already hand back.
  * `java.lang.reflect.Array` would shadow `kotlin.Array` in any file that
    imports it, so its import is dropped and its call sites are qualified.
  * `Map.Entry` becomes `MutableMap.MutableEntry`, with getKey()/getValue()
    as extensions.

Statics on types Kotlin already owns (`Long.parseLong`, `String.format`) cannot
be stubbed - importing a `java.lang.Long` of our own would shadow `kotlin.Long`
for the whole file.  They are extensions on the Kotlin companion instead, and
the import pass pulls them in by call site.
"""
