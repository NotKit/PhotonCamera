def transform(unit, ctx):
    if not ctx.get("_jdk_stubs_emitted"):
        ctx["_jdk_stubs_emitted"] = True
        emit_stubs(ctx["out_root"], ctx["stats"])

    text = unit.kotlin

    # java.lang.reflect.Array shadows kotlin.Array for the whole file.
    if _ARRAY_IMPORT.search(text):
        text = _ARRAY_IMPORT.sub("import java.lang.reflect.ArrayReflect", text)
        text = _ARRAY_CALL.sub(r"ArrayReflect.\1(", text)
        ctx["stats"]["jdk-stubs:reflect-array"] += 1

    n = len(_FACTORY.findall(text))
    if n:
        text = _FACTORY.sub(lambda m: "mutable%sOf(" % m.group(1), text)
        ctx["stats"]["jdk-stubs:list-of"] += n

    # Map.Entry -> MutableMap.MutableEntry
    n = len(_MAP_ENTRY.findall(text))
    if n:
        text = _MAP_ENTRY.sub("MutableMap.MutableEntry", text)
        ctx["stats"]["jdk-stubs:map-entry"] += n

    lines = text.split("\n")
    body = "\n".join(l for l in lines if not l.startswith("import "))
    have = set()
    for l in lines:
        if l.startswith("import "):
            have.add(l[len("import "):].strip())
    have_simple = {i.rsplit(".", 1)[-1] for i in have}

    add = []
    for simple, fqn in sorted(LANG_TYPES.items()):
        if fqn in have or simple in have_simple:
            continue
        if re.search(r"(?<![\w.])%s\b" % simple, body):
            add.append(fqn)
    for rx, fqn in EXT_TRIGGERS:
        if fqn not in have and rx.search(body):
            add.append(fqn)

    if add:
        out, done = [], False
        for l in lines:
            if not done and (l.startswith("import ") or l.startswith("package ")):
                # after the package line, before the first import
                if l.startswith("package "):
                    out.append(l)
                    continue
                out.extend("import " + a for a in add)
                done = True
            out.append(l)
        if not done:                       # no imports at all: append after package
            out = []
            for l in lines:
                out.append(l)
                if l.startswith("package ") and not done:
                    out.append("")
                    out.extend("import " + a for a in add)
                    done = True
        lines = out
        ctx["stats"]["jdk-stubs:imports"] += len(add)

    unit.kotlin = "\n".join(lines)
    unit.imports = [l for l in lines if l.startswith("import ")]
