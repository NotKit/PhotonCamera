"""Repairs that need a type the codemod does not have, keyed by source text.

Everything a text codemod can do from the Java AST alone is done by the rules
before this one.  What is left is the residue where the fix is obvious but
*only once you know the type of an expression*: `x == 0` where `x` is a
`long`, `f(n)` where the parameter is a `float`, an `object :` whose member
overrides nothing.  Kotlin's own type checker knows all of those, so this rule
takes them from it.

`typed_repairs.tsv` is a table of repairs generated by
`kn-run/gen_typed_repairs.py <konanc log>`, one per line:

    <relative .kt path>  <action>  <needle>  <replacement>

    expr   replace every occurrence of `needle` in that file
    stub   replace the body of the member whose header is `needle` (the
           `<replacement>` column is the 0-based occurrence of that header in
           the file) with `TODO()`

Rows are keyed by the *text* of the expression or declaration, not by a line
number, so the table survives an unrelated edit upstream in the file and can
be re-applied to a newer mozilla-central: a row whose needle no longer occurs
simply does nothing, and is reported as stale.

`expr` rows are honest conversions - `.toLong()`, `.toFloat()`, `.code` -
inserted where Java's implicit widening was.  `stub` rows are defeats: the
member's body is gone.  Both are counted separately in the run report, and the
stub count is the PoC's hollowness measure.
"""
import os
import re
from collections import Counter

ORDER = 990               # dead last: the table is keyed by the text of
                          # the *finished* file, so nothing may follow it
NAME = "typed-repairs"
DESCRIPTION = "type-directed residue: widen numerics, stub what is left"

TABLE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "typed_repairs.tsv")

_STR = re.compile(r'"(?:\\.|[^"\\])*"')


def _load():
    rows = []
    if not os.path.exists(TABLE):
        return rows
    with open(TABLE) as fh:
        for line in fh:
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 4:
                continue
            rel, action, needle, repl = parts
            rows.append((rel, action, needle.replace("\\n", "\n"),
                         repl.replace("\\n", "\n")))
    return rows


_ROWS = None


def _blank(line):
    return _STR.sub(lambda m: '"' + " " * (len(m.group(0)) - 2) + '"', line)


def _extent(lines, idx):
    """Index of the last line of the declaration that starts at `idx`.

    Brace and paren depth from the header line: a declaration ends on the
    first line where depth falls back to zero, which covers `fun f() {`,
    a multi-line signature, and a one-line `val x = f(1)` alike.
    """
    depth = 0
    i = idx
    while i < len(lines):
        for ch in _blank(lines[i]).split("//", 1)[0]:
            if ch in "{(":
                depth += 1
            elif ch in "})":
                depth -= 1
        if depth <= 0:
            return i
        i += 1
    return len(lines) - 1


def _stub_member(lines, idx):
    """Replace the body of the declaration starting at `lines[idx]`."""
    head = lines[idx]
    end = _extent(lines, idx)
    indent = head[:len(head) - len(head.lstrip())]
    stripped = head.strip()
    if re.match(r"(?:\w+\s+)*(?:val|var)\s", stripped):
        eq = head.find("=")
        if eq < 0:
            return idx, [head]
        return end, [head[:eq].rstrip() + " = TODO()"]
    brace = head.find("{")
    if brace >= 0 and "object :" not in head[:brace]:
        return end, [head[:brace].rstrip() + " {", indent + "    TODO()",
                     indent + "}"]
    eq = head.find("=")
    if eq >= 0:
        return end, [head[:eq].rstrip() + " = TODO()"]
    return end, [head.rstrip() + " { TODO() }"]


def transform(unit, ctx):
    global _ROWS
    if _ROWS is None:
        _ROWS = _load()
        ctx["stats"][NAME + ":table"] = len(_ROWS)
    rel = unit.rel + ".kt"
    mine = [r for r in _ROWS if r[0] == rel]
    if not mine:
        return

    text = unit.kotlin
    stale = 0
    for _, action, needle, repl in mine:
        if action != "expr":
            continue
        if needle not in text:
            stale += 1
            continue
        text += ""
        n = text.count(needle)
        text = text.replace(needle, repl)
        ctx["stats"][NAME + ":expr"] += n

    stubs = [r for r in mine if r[1] == "stub"]
    if stubs:
        lines = text.split("\n")
        # collect (line index, header) for every requested stub first, then
        # rewrite from the bottom so earlier indices stay valid
        targets = []
        for _, _, needle, occ in stubs:
            want = int(occ) if occ.isdigit() else 0
            seen = 0
            hit = None
            for i, ln in enumerate(lines):
                if ln.strip() == needle.strip():
                    if seen == want:
                        hit = i
                        break
                    seen += 1
            if hit is None:
                stale += 1
            else:
                targets.append(hit)
        for i in sorted(set(targets), reverse=True):
            end, block = _stub_member(lines, i)
            lines[i:end + 1] = block
            ctx["stats"][NAME + ":stub"] += 1
        text = "\n".join(lines)

    if stale:
        ctx["stats"][NAME + ":stale"] += stale
        unit.notes.append("typed-repairs: %d stale row(s) for %s" % (stale, rel))
    unit.kotlin = text
